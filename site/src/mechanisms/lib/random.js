// Seeded randomness, so every lab draws the same data for everyone on every visit.
// Math.random cannot be seeded; mulberry32 keeps one 32-bit state word and mixes it per draw.

export function mulberry32(seed) {
  let state = seed >>> 0;
  return function next() {
    state = (state + 0x6d2b79f5) >>> 0;
    let z = state;
    z = Math.imul(z ^ (z >>> 15), z | 1);
    z ^= z + Math.imul(z ^ (z >>> 7), z | 61);
    return ((z ^ (z >>> 14)) >>> 0) / 4294967296;
  };
}

// A standard normal draw by the Box-Muller transform; 1 - u keeps the logarithm finite.
export function normal(rng) {
  const u = 1 - rng();
  const v = rng();
  return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
}
